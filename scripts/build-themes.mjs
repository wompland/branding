// Generates DaisyUI v5 theme CSS from src/tokens/wompland.mjs (built from brands/*.json) and fails on WCAG contrast misses.
// Theme names: wompland-<brand slug>-<mode>, e.g. wompland-blogwomp-dark (the master is wompland-wompland-<mode>).
//
// Contrast policy: see contrastChecks() in src/brand/theme.js (PRODUCT.md: WCAG 2.2 AA + AAA body text).
//   tokens.checks / brands.<b>.checks add identity-specific pairs, each with its own minimum.
// The default theme is tokens.defaultBrand (the master, "wompland") in tokens.defaultMode; that brand's dark theme is prefersdark.
import { readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parse, formatHex } from 'culori';
import { contrastChecks, themeBlock } from '../src/brand/theme.js';

const root = resolve(import.meta.dirname, '..');
const tokenDir = resolve(root, 'src/tokens');
const outDir = resolve(root, 'src/themes');

let failures = 0;
const only = process.argv[2];

for (const file of readdirSync(tokenDir).filter((f) => f.endsWith('.mjs'))) {
  const id = file.replace('.mjs', '');
  if (only && only !== id) continue;
  const { default: t } = await import(pathToFileURL(resolve(tokenDir, file)).href + `?t=${Date.now()}`);
  const defaultBrand = t.defaultBrand ?? 'womp';
  const blocks = [];
  const report = [];

  for (const [brand, modes] of Object.entries(t.brands)) {
    for (const mode of ['light', 'dark']) {
      const c = { ...t.modes[mode], ...modes[mode] };
      const name = `${id}-${brand}-${mode}`;
      // Identity-specific pairs: checks: { light|dark: [[label, fg, bg, min]] }; brand-level checks apply to that brand only.
      const checks = contrastChecks(c, [...(t.checks?.[mode] ?? []), ...(modes.checks?.[mode] ?? [])]);

      for (const k of checks.filter((x) => !x.pass)) {
        failures++;
        console.error(`✗ ${name}: ${k.label} = ${k.ratio} (needs ${k.min})  ${k.fg} / ${k.bg}`);
      }
      report.push({ theme: name, brand, mode, colors: Object.fromEntries(Object.entries(c).map(([k, v]) => [k, formatHex(parse(v))])), checks });

      blocks.push(
        themeBlock({
          name,
          mode,
          colors: c,
          shape: t.shape,
          vars: { ...(t.extra?.[mode] ?? {}), ...(modes.extra?.[mode] ?? {}) },
          isDefault: brand === defaultBrand && mode === t.defaultMode,
          prefersDark: brand === defaultBrand && mode === 'dark',
        }),
      );
    }
  }

  writeFileSync(
    resolve(outDir, `${id}.css`),
    `/* Generated by scripts/build-themes.mjs from src/tokens/${file}. Do not edit. */\n\n${blocks.join('\n\n')}\n`,
  );
  writeFileSync(resolve(outDir, `${id}.report.json`), JSON.stringify(report, null, 2) + '\n');
  const total = report.reduce((n, r) => n + r.checks.length, 0);
  const bad = report.reduce((n, r) => n + r.checks.filter((c) => !c.pass).length, 0);
  console.log(`${bad ? '✗' : '✓'} ${id}: ${report.length} themes, ${total - bad}/${total} contrast checks pass`);
}

if (failures) {
  console.error(`\n${failures} contrast failure(s). Fix the tokens; themes were written but do not meet PRODUCT.md accessibility.`);
  process.exit(1);
}
